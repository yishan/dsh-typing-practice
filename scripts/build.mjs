import { build } from 'esbuild';
import { readFile, readdir, writeFile, utimes } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { validateCorpus } from './check-corpus.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
console.log('Corpus:', validateCorpus());
const bundledPackages = new Set();
function trackDependencies(result) {
  for (const input of Object.keys(result.metafile.inputs)) {
    const name = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input)?.[1];
    if (name) bundledPackages.add(name);
  }
}
// Ship a self-contained Host entry as well as Client chunks. GitHub installs
// and local directory links must work without this checkout's node_modules.
const host = await build({ entryPoints: [resolve(root, 'src/host.js')], bundle: true,
  platform: 'node', format: 'esm', target: 'node22', minify: true, charset: 'utf8',
  legalComments: 'inline', metafile: true, write: false,
  banner: { js: '// Generated by npm run build; see src/host.js and THIRD_PARTY_NOTICES.md.' } });
for (const output of Object.values(host.metafile.outputs)) {
  if (output.imports.some(item => !item.path.startsWith('node:'))) throw new Error('Host bundle has an external runtime dependency');
}
trackDependencies(host);
await writeFile(resolve(root, 'index.js'), host.outputFiles[0].text);
console.log(`index.js: ${host.outputFiles[0].contents.length} bytes`);
// Keep the curated text synchronously available, including offline startup.
// Only this marked block is generated; the rest of client.js is hand-written.
const practice = await build({ entryPoints: [resolve(root, 'src/practice-text.js')], bundle: true,
  platform: 'browser', format: 'cjs', target: 'es2022', minify: true, charset: 'utf8', write: false });
const start = '    // BEGIN GENERATED PRACTICE CORPUS';
const end = '    // END GENERATED PRACTICE CORPUS';
const clientPath = resolve(root, 'client.js');
const client = await readFile(clientPath, 'utf8');
const from = client.indexOf(start), to = client.indexOf(end);
if (from < 0 || to <= from) throw new Error('Missing corpus build markers');
const block = `${start}\n    const PracticeCorpus = (() => { const module = { exports: {} }; const exports = module.exports;\n${practice.outputFiles[0].text}\nreturn module.exports; })();\n${end}`;
await writeFile(clientPath, client.slice(0, from) + block + client.slice(to + end.length));
// Each DSH chunk is self-contained. No CDN, runtime ESM, or relative require.
for (const name of ['pinyin', 'jyutping']) {
  const chunk = `client.${name}.js`;
  const result = await build({
    entryPoints: [resolve(root, `src/${name}.js`)], bundle: true,
    platform: 'browser', format: 'cjs', target: 'es2022',
    minify: true, charset: 'utf8', legalComments: 'inline', metafile: true, write: false,
  });
  trackDependencies(result);
  const wrapper = `// Generated by npm run build; see THIRD_PARTY_NOTICES.md.\nwindow.__ModuleLoader__.load({id:'typing-practice',chunk:'${chunk}',factory(require){const module={exports:{}};const exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;}});\n`;
  await writeFile(resolve(root, chunk), wrapper);
  console.log(`${chunk}: ${Buffer.byteLength(wrapper)} bytes`);
}
// Embed the small MP3 recordings in a local DSH chunk. Runtime playback needs
// neither a public asset URL nor a remote request, including on dsh-app://.
const audioManifest = JSON.parse(await readFile(resolve(root, 'assets/audio/kbsim/manifest.json'), 'utf8'));
const samples = {};
for (const file of audioManifest.files.filter(item => item.path.endsWith('.mp3'))) {
  const data = await readFile(resolve(root, 'assets/audio/kbsim', file.path));
  if (createHash('sha256').update(data).digest('hex') !== file.sha256) throw new Error(`Audio checksum mismatch: ${file.path}`);
  const [pack, , name] = file.path.split('/');
  (samples[pack] ??= {})[name.replace('.mp3', '')] = data.toString('base64');
}
const audio = await build({ entryPoints: [resolve(root, 'src/audio-player.js')], bundle: true,
  platform: 'browser', format: 'cjs', target: 'es2022', minify: true, write: false });
const audioChunk = `// Generated by npm run build. kbsim recordings: Copyright (c) Thomas Lai, MIT. See THIRD_PARTY_NOTICES.md.\nwindow.__ModuleLoader__.load({id:'typing-practice',chunk:'client.audio.js',factory(require){const module={exports:{}};const exports=module.exports;\n${audio.outputFiles[0].text}\nreturn {...module.exports,samples:${JSON.stringify(samples)}};}});\n`;
await writeFile(resolve(root, 'client.audio.js'), audioChunk);
console.log(`client.audio.js: ${Buffer.byteLength(audioChunk)} bytes`);
let notices = '# Third-party notices\n\nPronunciation engines are bundled locally in their respective Client chunks. The Host bundles mdast-util-from-markdown and its runtime dependencies to parse selected conversation text. All bundled package licenses are included below. Built-in practice passages are authored in this project.\n';
for (const name of [...bundledPackages].sort()) {
  const manifest = JSON.parse(await readFile(resolve(root, `node_modules/${name}/package.json`), 'utf8'));
  const licenseFile = (await readdir(resolve(root, `node_modules/${name}`), { withFileTypes: true }))
    .find(entry => entry.isFile() && /^licen[cs]e(?:[.-].*)?$/i.test(entry.name));
  if (!licenseFile) throw new Error(`Missing bundled license: ${name}`);
  const license = await readFile(resolve(root, `node_modules/${name}`, licenseFile.name), 'utf8');
  notices += `\n## ${name} ${manifest.version}\n\n${typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url || manifest.homepage || ''}\n\n${license}\n`;
}
notices += `\n## kbsim keyboard recordings\n\n${audioManifest.repository}/tree/${audioManifest.revision}/src/assets/audio\n\nCherry MX Blue, Cherry MX Brown, NovelKeys Cream and Holy Panda press samples are bundled unchanged in client.audio.js. Five general-key variations are included for each pack; dedicated space, backspace and enter samples are used where the upstream pack provides them. The audio is licensed under the upstream MIT license below. Product names identify the recordings, without implying affiliation.\n\n${await readFile(resolve(root, 'assets/audio/kbsim/LICENSE.md'), 'utf8')}\n`;
await writeFile(resolve(root, 'THIRD_PARTY_NOTICES.md'), notices.trimEnd() + '\n');
// DSH derives the owner revision from the entry metadata, not sibling chunks.
// Stamp the owner only after all its chunks have been written.
const now = new Date();
await utimes(resolve(root, 'client.js'), now, now);
